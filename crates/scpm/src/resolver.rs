//! The resolver sidecar (design §5.2.1): coursier as a library in a JVM scpm starts itself,
//! sealed from every ambient setting, speaking JSON lines. In M1 it is opt-in
//! (`SCPM_RESOLVER=sidecar`), one process per command.
//!
//! Its own jars can't be resolved by it, so each scpm release carries their list
//! ([`BOOTSTRAP_LIST`]: name, sha256 and size per jar), and they are restored straight from the
//! release (or `resolverMirror`) into `<cache>/scpm/resolver/<sha256>.jar`.

use std::collections::BTreeMap;
use std::ffi::OsString;
use std::path::{Path, PathBuf};
use std::time::Duration;

use serde::{Deserialize, Serialize};
use serde_json::{Value, json};

use crate::coursier::{self, Auth, Repo, ResolveRequest, ResolvedArtifact};
use crate::credentials::CoursierCredentials;
use crate::fetch::{self, FetchItem, FetchOptions};
use crate::machine::{Machine, ProxyServer};
use crate::worker::{Spawn, Worker, WorkerError};

/// The list built into this scpm (generated by `sbt resolver/bootstrapList` in `worker/`).
pub const BOOTSTRAP_LIST: &str = include_str!("../../../worker/resolver/bootstrap.txt");

/// Where release assets are downloaded from: `<base>/<release>/<jar>`.
pub const RELEASE_BASE: &str = "https://github.com/gatorcse/scpm/releases/download";

/// Replaces the pinned jars with a local classpath (development; prints a notice).
pub const CLASSPATH_ENV: &str = "SCPM_RESOLVER_CLASSPATH";

/// `cs` (the default in M1) or `sidecar`.
pub const RESOLVER_ENV: &str = "SCPM_RESOLVER";

/// Hidden, for tests: a bootstrap list file to use instead of the built-in one (and instead of
/// a source checkout's locally built jars).
const TEST_LIST_ENV: &str = "SCPM_TEST_RESOLVER_LIST";

const PROTOCOL_VERSION: u64 = 1;
const MAIN_CLASS: &str = "scpm.resolver.Main";

#[derive(Debug, thiserror::Error)]
pub enum ResolverError {
    #[error("{0}")]
    Setup(String),
    #[error(transparent)]
    Worker(#[from] WorkerError),
    #[error("{0}")]
    Fetch(fetch::FetchFailure),
}

/// One jar of the bootstrap list.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct BootstrapJar {
    pub sha256: String,
    pub size: u64,
    pub name: String,
}

/// The bootstrap list: the release its jars were uploaded to (`None` for a development list),
/// and the jars in classpath order.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct BootstrapList {
    pub release: Option<String>,
    pub jars: Vec<BootstrapJar>,
}

impl BootstrapList {
    pub fn parse(text: &str) -> Result<BootstrapList, String> {
        let mut release = None;
        let mut jars = Vec::new();
        for (n, line) in text.lines().enumerate() {
            let line = line.trim();
            if line.is_empty() || line.starts_with('#') {
                continue;
            }
            let bad = || format!("line {}: expected `<sha256> <size> <name>`: {line}", n + 1);
            if let Some(r) = line.strip_prefix("release ") {
                release = Some(r.trim()).filter(|r| *r != "none").map(str::to_string);
                continue;
            }
            let mut parts = line.split_whitespace();
            let (Some(sha256), Some(size), Some(name), None) = (parts.next(), parts.next(), parts.next(), parts.next())
            else {
                return Err(bad());
            };
            let size = size.parse().map_err(|_| bad())?;
            let safe = !name.is_empty() && !name.contains(['/', '\\']) && name != "." && name != "..";
            if sha256.len() != 64 || !sha256.bytes().all(|b| b.is_ascii_hexdigit()) || !safe {
                return Err(bad());
            }
            jars.push(BootstrapJar { sha256: sha256.to_ascii_lowercase(), size, name: name.to_string() });
        }
        if jars.is_empty() {
            return Err("it lists no jars".into());
        }
        Ok(BootstrapList { release, jars })
    }

    /// Where each jar is downloaded from: `resolverMirror`, else the release's assets, plus the
    /// asset name `<sha256>.jar`. Content-addressed, so one mirror directory serves every
    /// release, and an asset can never be replaced by other bytes under the same name.
    pub fn urls(&self, mirror: Option<&str>) -> Option<Vec<String>> {
        let base = match (mirror, &self.release) {
            (Some(m), _) => m.to_string(),
            (None, Some(r)) => format!("{RELEASE_BASE}/{r}/"),
            (None, None) => return None,
        };
        Some(self.jars.iter().map(|j| format!("{base}{}.jar", j.sha256)).collect())
    }
}

/// `<cache>/scpm/resolver`: the pinned jars, and the sidecar's private `user.home` and
/// coursier configuration directory.
pub fn cache_dir() -> Result<PathBuf, ResolverError> {
    dirs::cache_dir()
        .map(|c| c.join("scpm/resolver"))
        .ok_or_else(|| ResolverError::Setup("cannot find the user cache directory".into()))
}

/// The resolver's classpath, and a notice when it isn't pinned by the built-in list.
pub fn classpath(machine: &Machine) -> Result<(Vec<PathBuf>, Option<String>), ResolverError> {
    if let Some(cp) = std::env::var_os(CLASSPATH_ENV).filter(|c| !c.is_empty()) {
        let jars: Vec<PathBuf> = std::env::split_paths(&cp).collect();
        let notice = format!(
            "{CLASSPATH_ENV} replaces the resolver's jars, which are then not checked against the sha256 values built into scpm"
        );
        return Ok((jars, Some(notice)));
    }
    // The hidden test list exists in debug builds only, so a release binary's pins can't be
    // swapped by an environment variable.
    let test_list =
        if cfg!(debug_assertions) { std::env::var_os(TEST_LIST_ENV).filter(|c| !c.is_empty()) } else { None };
    let text = match &test_list {
        Some(path) => std::fs::read_to_string(path)
            .map_err(|e| ResolverError::Setup(format!("{}: {e}", Path::new(&path).display())))?,
        None => BOOTSTRAP_LIST.to_string(),
    };
    let list = BootstrapList::parse(&text)
        .map_err(|e| ResolverError::Setup(format!("the resolver's built-in jar list is invalid: {e}")))?;
    // A source checkout's own jars stand in for a development list, which names no release. A
    // released list keeps its pins: only a debug build (a developer's) uses the checkout's jars
    // over it, and says so as for SCPM_RESOLVER_CLASSPATH.
    if test_list.is_none()
        && (list.release.is_none() || cfg!(debug_assertions))
        && let Some((dir, jars)) = local_build()
    {
        if list.release.is_none() {
            return Ok((jars, None));
        }
        let notice = format!(
            "using the resolver jars built in {}, which are not checked against the sha256 values built into scpm",
            dir.display()
        );
        return Ok((jars, Some(notice)));
    }
    Ok((restore(&list, machine)?, None))
}

/// A source checkout's locally built jars (`sbt resolver/stage` in `worker/`), as the compile
/// worker finds its own: `worker/target/out/jvm/resolver-stage` above the running binary.
fn local_build() -> Option<(PathBuf, Vec<PathBuf>)> {
    let exe = std::env::current_exe().ok()?;
    exe.ancestors().find_map(|dir| {
        let stage = dir.join("worker/target/out/jvm/resolver-stage");
        let names = std::fs::read_to_string(stage.join("classpath.txt")).ok()?;
        let jars: Vec<PathBuf> =
            names.lines().map(str::trim).filter(|l| !l.is_empty()).map(|n| stage.join(n)).collect();
        jars.iter().all(|j| j.is_file()).then_some((stage, jars))
    })
}

/// Downloads the listed jars (no credentials, the machine's proxy) into the cache, each checked
/// against its sha256, and returns their paths in classpath order.
fn restore(list: &BootstrapList, machine: &Machine) -> Result<Vec<PathBuf>, ResolverError> {
    let urls = list.urls(machine.resolver_mirror.as_deref()).ok_or_else(|| {
        ResolverError::Setup(format!(
            "this scpm build names no release for the resolver sidecar's jars (a development build)\n  help: in a \
             source checkout, run `sbt resolver/stage` in worker/; or set {CLASSPATH_ENV} to the resolver's \
             classpath, or `resolverMirror` in the user config to a server holding the jars"
        ))
    })?;
    let dir = cache_dir()?;
    let items: Vec<FetchItem> = list
        .jars
        .iter()
        .zip(urls)
        .map(|(jar, url)| FetchItem {
            key: format!("resolver {}", jar.name),
            url,
            dest: dir.join(format!("{}.jar", jar.sha256)),
            sha256: jar.sha256.clone(),
            size: jar.size,
            // The assets are public: credentials never go there, whatever the user config matches.
            auth: Ok(None),
            challenge: Vec::new(),
            verify_cached: false,
            fallbacks: Vec::new(),
        })
        .collect();
    let paths = items.iter().map(|i| i.dest.clone()).collect();
    fetch::fetch_all(items, FetchOptions { verify: false, proxy: machine.proxy.clone() })
        .map_err(ResolverError::Fetch)?;
    Ok(paths)
}

/// The system PEM bundle the Rust TLS stack would use on Linux (`SSL_CERT_FILE`, then the
/// distributions' usual paths). `None` elsewhere: macOS and Windows have OS stores.
fn pem_bundle() -> Option<PathBuf> {
    if !cfg!(target_os = "linux") {
        return None;
    }
    // Absolute: the sidecar runs in its private home, not scpm's working directory.
    let from_env = std::env::var_os("SSL_CERT_FILE")
        .map(PathBuf::from)
        .filter(|p| p.is_file())
        .map(|p| std::path::absolute(&p).unwrap_or(p));
    from_env.or_else(|| {
        [
            "/etc/ssl/certs/ca-certificates.crt",
            "/etc/pki/tls/certs/ca-bundle.crt",
            "/etc/ssl/ca-bundle.pem",
            "/etc/pki/tls/cacert.pem",
            "/etc/pki/ca-trust/extracted/pem/tls-ca-bundle.pem",
            "/etc/ssl/cert.pem",
        ]
        .iter()
        .map(PathBuf::from)
        .find(|p| p.is_file())
    })
}

/// The variables a sealed sidecar keeps: locale (so non-ASCII cache paths decode as for scpm),
/// and on Windows what the OS needs. Everything else (`JAVA_TOOL_OPTIONS`, `COURSIER_*`, …)
/// is cleared.
/// Values are kept as they are (not necessarily UTF-8); names that aren't UTF-8 are none of these.
fn allowed_env(inherited: impl Iterator<Item = (OsString, OsString)>) -> Vec<(OsString, OsString)> {
    const WINDOWS: &[&str] = &["SYSTEMROOT", "SYSTEMDRIVE", "WINDIR", "TEMP", "TMP"];
    inherited
        .filter(|(k, _)| {
            let Some(upper) = k.to_str().map(str::to_ascii_uppercase) else { return false };
            upper == "LANG" || upper.starts_with("LC_") || (cfg!(windows) && WINDOWS.contains(&upper.as_str()))
        })
        .collect()
}

fn private_dir(path: &Path) -> Result<(), ResolverError> {
    let err = |e: std::io::Error| ResolverError::Setup(format!("cannot create {}: {e}", path.display()));
    std::fs::create_dir_all(path).map_err(err)?;
    #[cfg(unix)]
    {
        use std::os::unix::fs::PermissionsExt;
        std::fs::set_permissions(path, std::fs::Permissions::from_mode(0o700)).map_err(err)?;
    }
    Ok(())
}

/// A running sidecar, for one command.
pub struct Sidecar {
    worker: Worker,
    /// Set when the jars aren't pinned (`SCPM_RESOLVER_CLASSPATH`).
    pub notice: Option<String>,
    timeouts: Timeouts,
}

#[derive(Serialize)]
struct ProxyParam<'a> {
    #[serde(skip_serializing_if = "Option::is_none")]
    http: Option<&'a ProxyServer>,
    #[serde(skip_serializing_if = "Option::is_none")]
    https: Option<&'a ProxyServer>,
    #[serde(rename = "noProxy")]
    no_proxy: &'a [String],
}

impl Sidecar {
    /// Starts the sidecar on the JDK `detect_java` finds (JDK 17 or newer) and initializes it.
    pub fn start(machine: &Machine) -> Result<Sidecar, ResolverError> {
        // The JDK's own binary, the one whose `release` file was read: a shim or wrapper on PATH
        // (asdf, jenv, mise, a site script) may not work in the sealed environment, or pick
        // another JDK there.
        let home = crate::system::worker_jdk().ok_or_else(|| {
            ResolverError::Setup(format!(
                "the resolver sidecar needs a JDK {}+, and no JDK home was found (only a `java` without one, or \
                 none)\n  help: set SCPM_JAVA_HOME to a JDK",
                crate::worker::MIN_JAVA
            ))
        })?;
        let java = crate::worker::java_in_home(&home, "the detected JDK home")?;
        let (classpath, notice) = classpath(machine)?;
        // Said when the sidecar starts, so a failing command shows it too.
        if let Some(n) = &notice {
            eprintln!("note: {n}");
        }
        let dir = cache_dir()?;
        let home = dir.join("home");
        let config = dir.join("empty-config");
        private_dir(&home)?;
        private_dir(&config)?;
        let jvm_options = vec![
            "-XX:TieredStopAtLevel=1".to_string(),
            "-Xmx512m".to_string(),
            "-XX:-UsePerfData".to_string(),
            "-XX:+DisableAttachMechanism".to_string(),
            format!("-Duser.home={}", home.display()),
            format!("-Dcoursier.config-dir={}", config.display()),
            format!("-Dscala-cli.config={}", config.join("absent.json").display()),
        ];
        let spec = Spawn {
            name: "the resolver sidecar",
            classpath: &classpath,
            main: MAIN_CLASS,
            jvm_options: &jvm_options,
            env: allowed_env(std::env::vars_os()),
            cwd: Some(&home),
            log_file: None,
            initialize: false,
            own_process_group: false,
            clear_env: true,
            java: Some(java),
        };
        let worker = Worker::spawn(spec, |_| {})?;
        // A scheme whose environment proxy is unusable goes to a host that never resolves, as
        // for `cs` (requests that need it were refused before starting).
        let unusable = ProxyServer { host: crate::machine::UNUSABLE_PROXY_HOST.into(), port: 80 };
        let proxy = machine.proxy.as_ref().map(|p| {
            let pick = |scheme: &str, server: &Option<ProxyServer>| {
                if p.errors.contains_key(scheme) { Some(unusable.clone()) } else { server.clone() }
            };
            (pick("http", &p.http), pick("https", &p.https), p.no_proxy.clone())
        });
        let proxy = proxy.as_ref().map(|(http, https, no_proxy)| ProxyParam {
            http: http.as_ref(),
            https: https.as_ref(),
            no_proxy,
        });
        let sidecar = Sidecar { worker, notice, timeouts: Timeouts::get() };
        let init = sidecar.call(
            "initialize",
            json!({
                "protocolVersion": PROTOCOL_VERSION,
                "proxy": proxy,
                "trust": {"pemBundle": pem_bundle()},
                "userAgent": coursier::user_agent(),
            }),
            sidecar.timeouts.initialize,
        )?;
        if init["protocolVersion"].as_u64() != Some(PROTOCOL_VERSION) {
            return Err(ResolverError::Setup(format!(
                "the resolver sidecar speaks protocol {}, expected {PROTOCOL_VERSION}",
                init["protocolVersion"]
            )));
        }
        Ok(sidecar)
    }

    /// A request that must be answered within `limit`; otherwise the sidecar is killed.
    /// The deadline starts before the request is written, and a watchdog kills the process when
    /// it passes: a JVM that stops reading its input would otherwise block the write itself.
    fn call(&self, method: &str, params: Value, limit: Duration) -> Result<Value, ResolverError> {
        let (done, finished) = std::sync::mpsc::channel::<()>();
        // `(replied, expired)`, decided under one lock: a reply that lands right at the deadline
        // is either used (and the process lives on) or dropped (and the process killed), never
        // used with the process killed behind it.
        let state = std::sync::Mutex::new((false, false));
        let result = std::thread::scope(|s| {
            let state = &state;
            s.spawn(move || {
                if let Err(std::sync::mpsc::RecvTimeoutError::Timeout) = finished.recv_timeout(limit) {
                    let mut st = state.lock().expect("call state");
                    if !st.0 {
                        st.1 = true;
                        self.worker.kill("was stopped: it did not answer in time");
                    }
                }
            });
            let result = self.worker.request(method, params);
            let mut st = state.lock().expect("call state");
            if !st.1 {
                st.0 = true;
            }
            drop(st);
            let _ = done.send(());
            result
        });
        let expired = state.lock().expect("call state").1;
        match result {
            _ if expired => Err(WorkerError::Timeout(format!(
                "the resolver sidecar did not answer `{method}` within {}s, and was stopped",
                limit.as_secs_f64().ceil()
            ))
            .into()),
            other => Ok(other?),
        }
    }

    /// Resolves every request in one call (the sidecar runs them concurrently). Each result is
    /// the request's [`Resolution`](crate::install::Resolution), or its error as text.
    pub fn resolve(
        &self,
        requests: &[&ResolveRequest],
        systems: &[String],
        jdk: &str,
        repos: &[Repo],
        cache: &Path,
    ) -> Result<Vec<Result<crate::install::Resolution, String>>, ResolverError> {
        let repositories = repository_params(repos)?;
        let requests: Vec<Value> = requests
            .iter()
            .enumerate()
            .map(|(i, r)| {
                json!({
                    "label": format!("request {i}"),
                    "systems": systems,
                    "jdk": r.jdk_version.as_deref().unwrap_or(jdk),
                    "natives": r.natives,
                    "roots": roots(r),
                    "boms": r.boms,
                    "forced": r.forced,
                    "artifactTypes": coursier::artifact_types(r),
                })
            })
            .collect();
        let result = self.call(
            "resolve",
            json!({"repositories": repositories, "cache": cache, "requests": requests}),
            self.timeouts.request,
        )?;
        let results: Vec<RequestResult> = serde_json::from_value(result["results"].clone())
            .map_err(|e| ResolverError::Setup(format!("the resolver sidecar answered `resolve` with {e}")))?;
        Ok(results.into_iter().map(RequestResult::resolution).collect())
    }

    /// The versions of `org:name` in the repositories its group may come from, ascending.
    pub fn list_versions(&self, module: &str, repos: &[Repo], cache: &Path) -> Result<Vec<String>, ResolverError> {
        let result = self.call(
            "listVersions",
            json!({"repositories": repository_params(repos)?, "cache": cache, "module": module}),
            self.timeouts.request,
        )?;
        Ok(result["versions"].as_array().into_iter().flatten().filter_map(|v| v.as_str().map(str::to_string)).collect())
    }

    /// Asks the sidecar to exit, and kills it if it doesn't within the shutdown timeout.
    pub fn shutdown(self) {
        let _ = self.worker.request_timeout("shutdown", json!({}), Some(self.timeouts.shutdown));
        self.worker.close(Some(self.timeouts.shutdown));
    }
}

/// How long the sidecar may take: to start and answer `initialize`, to answer one `resolve` or
/// `listVersions` (a whole cold re-lock), and to exit after `shutdown`.
#[derive(Debug, Clone, Copy)]
struct Timeouts {
    initialize: Duration,
    request: Duration,
    shutdown: Duration,
}

impl Timeouts {
    fn get() -> Timeouts {
        // Hidden, debug builds only: one short limit for everything, for tests.
        #[cfg(debug_assertions)]
        if let Some(ms) = std::env::var("SCPM_TEST_RESOLVER_TIMEOUT_MS").ok().and_then(|v| v.parse().ok()) {
            let d = Duration::from_millis(ms);
            return Timeouts { initialize: d, request: d, shutdown: d };
        }
        Timeouts {
            initialize: Duration::from_secs(60),
            request: Duration::from_secs(30 * 60),
            shutdown: Duration::from_secs(10),
        }
    }
}

/// The repositories as the sidecar takes them (design §5.2.1): every one in declared order,
/// mirrors applied, `groups`, and credentials after scpm's policy, matched by origin as `cs` and
/// the fetcher do (two repositories on one origin with different credentials are refused, as
/// for `cs`). A bearer token goes as basic auth for the user `token`; an entry from coursier's
/// own sources scoped to a realm keeps it.
fn repository_params(repos: &[Repo]) -> Result<Vec<Value>, ResolverError> {
    repository_params_with(repos, &CoursierCredentials::load())
}

fn repository_params_with(repos: &[Repo], creds: &CoursierCredentials) -> Result<Vec<Value>, ResolverError> {
    let shared = coursier::shared_credentials(repos, &|var| std::env::var(var).ok(), &mut Vec::new())
        .map_err(|e| ResolverError::Setup(e.to_string()))?;
    let coursier_creds = creds.restricted(&coursier::insecure_credential_origins(repos));
    Ok(repos
        .iter()
        .zip(shared)
        .map(|(r, shared)| {
            let url = r.fetch_url();
            let (auth, challenges) = match shared {
                Some(a @ (Auth::Basic { .. } | Auth::Bearer(_))) => {
                    (Some(json!({"user": a.user(), "password": a.password()})), Vec::new())
                }
                None => match coursier_creds.find(url) {
                    Some(c) => (Some(json!({"user": c.user, "password": c.password})), Vec::new()),
                    // Every realm-scoped entry: the challenge decides which one applies.
                    None => (
                        None,
                        coursier_creds
                            .challenge_candidates(url)
                            .iter()
                            .map(|c| json!({"user": c.user, "password": c.password, "realm": c.realm}))
                            .collect(),
                    ),
                },
            };
            let mut v = json!({"id": r.id, "url": url});
            if !r.groups.is_empty() {
                v["groups"] = json!(r.groups);
            }
            if let Some(a) = auth {
                v["auth"] = a;
            }
            if !challenges.is_empty() {
                v["challenges"] = json!(challenges);
            }
            v
        })
        .collect())
}

/// A request's roots from `cs`-syntax dependency strings (`org:name:version,exclude=o%n,…`).
fn roots(req: &ResolveRequest) -> Vec<Value> {
    let root = |dep: &str, transitive: bool| {
        let mut parts = dep.split(',');
        let coord: Vec<&str> = parts.next().unwrap_or_default().split(':').collect();
        let mut v = json!({
            "module": format!("{}:{}", coord.first().unwrap_or(&""), coord.get(1).unwrap_or(&"")),
            "version": coord.get(2).unwrap_or(&""),
            "transitive": transitive,
        });
        let mut exclusions = Vec::new();
        for p in parts {
            if let Some(e) = p.strip_prefix("exclude=") {
                exclusions.push(e.replacen('%', ":", 1));
            } else if let Some(c) = p.strip_prefix("classifier=") {
                v["classifier"] = json!(c);
            } else if let Some(t) = p.strip_prefix("type=") {
                v["type"] = json!(t);
            }
        }
        v["exclusions"] = json!(exclusions);
        v
    };
    req.dependencies.iter().map(|d| root(d, true)).chain(req.intransitive.iter().map(|d| root(d, false))).collect()
}

#[derive(Debug, Deserialize)]
struct Entry {
    group: String,
    artifact: String,
    version: String,
    classifier: Option<String>,
    url: String,
    file: PathBuf,
    systems: Option<Vec<String>>,
}

impl Entry {
    /// The lock key, by the one key function `cs` results go through too.
    fn artifact(&self) -> Result<ResolvedArtifact, String> {
        let coord = match &self.classifier {
            Some(c) => format!("{}:{}:jar:{c}:{}", self.group, self.artifact, self.version),
            None => format!("{}:{}:{}", self.group, self.artifact, self.version),
        };
        let key = coursier::artifact_key(&coord, &self.file).ok_or_else(|| format!("invalid coordinate {coord}"))?;
        Ok(ResolvedArtifact { key, file: self.file.clone(), url: self.url.clone() })
    }
}

#[derive(Debug, Deserialize)]
#[serde(rename_all = "camelCase")]
struct RequestResult {
    classpath: Option<Vec<Entry>>,
    by_system: Option<BTreeMap<String, Vec<Entry>>>,
    error: Option<ErrorBody>,
}

#[derive(Debug, Deserialize)]
struct ErrorBody {
    code: String,
    message: String,
    data: Option<Value>,
}

impl ErrorBody {
    fn describe(&self) -> String {
        let mut out = format!("{} ({})", self.message, self.code);
        for t in self.data.as_ref().and_then(|d| d["tried"].as_array()).into_iter().flatten() {
            out.push_str(&format!(
                "\n  tried {} ({}): {}",
                t["url"].as_str().unwrap_or_default(),
                t["repository"].as_str().unwrap_or_default(),
                t["status"].as_str().unwrap_or_default()
            ));
        }
        out
    }
}

impl RequestResult {
    fn resolution(self) -> Result<crate::install::Resolution, String> {
        use crate::install::Resolution;
        if let Some(e) = self.error {
            return Err(e.describe());
        }
        if let Some(list) = self.classpath {
            return list
                .into_iter()
                .map(|e| Ok((e.artifact()?, e.systems.clone())))
                .collect::<Result<_, String>>()
                .map(Resolution::Merged);
        }
        let by = self.by_system.ok_or("the resolver sidecar answered with neither a classpath nor an error")?;
        by.into_iter()
            .map(|(s, list)| Ok((s, list.iter().map(Entry::artifact).collect::<Result<Vec<_>, String>>()?)))
            .collect::<Result<_, String>>()
            .map(Resolution::BySystem)
    }
}

