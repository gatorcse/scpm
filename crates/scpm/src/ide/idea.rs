//! `scpm idea`: native IntelliJ project files (design §10.2, path 2), in the shapes Mill's
//! GenIdea writes (com-lihaoyi/mill `runner/idea/src/mill/idea/GenIdeaImpl.scala` and the
//! expected files under `integration/feature/gen-idea/resources/`, at commit
//! cf391cdbf097653c45770682449754e6f992121c, 2026-11-25), with IntelliJ's own JPS build.
//!
//! - One IntelliJ module per scpm module: its *primary* variant (`ide.primary`, default the
//!   first variant, i.e. the first Scala version listed). IntelliJ can't have two modules share
//!   a content root, so the other variants of a cross-built module are not IntelliJ modules.
//!   Main and test sources share the module (test folders are `isTestSource`), as Maven and
//!   Gradle imports do.
//! - Dependencies come from the lock's four classpaths. An entry on the compile and runtime
//!   classpaths is COMPILE (no scope), compile only is PROVIDED, runtime only is RUNTIME, and
//!   test classpaths only is TEST. Libraries are project libraries named `scpm: <lock key>`;
//!   workspace dependencies are module dependencies, or, when the upstream variant isn't its
//!   module's primary one, a module library on scpm's own output (`.scpm/out/<id>/classes`).
//! - Each Scala version gets a Scala SDK library (`type="Scala"`, `<language-level>`,
//!   `<compiler-classpath>` from the lock's boot section); scalac options and compiler plugins
//!   go to `scala_compiler.xml` profiles.
//! - IntelliJ compiles into `.scpm/idea-out/<id>/`, never into scpm's `.scpm/out/`.
//! - Only scpm's files are written: `modules.xml` (keeping entries for modules scpm didn't
//!   generate), `modules/<module>.iml`, `libraries/scpm__*.xml`, `scala_compiler.xml` and
//!   `misc.xml`. Each starts with a "Generated by scpm" comment. A file is (re)written only when
//!   it doesn't exist, still carries that comment, or is listed in `.scpm/idea-out/generated`
//!   (the files scpm wrote last time; IntelliJ drops comments when it re-saves a file).
//!   Anything else is someone else's and is skipped with a warning, unless `--force`.
//!   `misc.xml`, where the IDE keeps the project JDK, is stricter: only when missing or still
//!   carrying the comment. Files generated earlier and no longer needed are deleted.

