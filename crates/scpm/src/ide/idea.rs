const MARKER: &str = "<!-- Generated by scpm (`scpm idea`); regenerated by `scpm install`. Edit scpm.yaml instead. -->";
const MANIFEST: &str = ".scpm/idea-out/generated";

#[derive(Debug, Clone, Default)]
pub struct Options {
    /// Whether to download sources jars that aren't cached yet.
    pub sources: SourcesOptions,
    /// Overwrite IntelliJ files scpm didn't generate (`--force`).
    pub force: bool,
}

#[derive(Debug, Default, Serialize)]
#[serde(rename_all = "camelCase")]
pub struct Summary {
    /// Files written because they changed (relative to the workspace root).
    pub written: Vec<String>,
    /// Files scpm generated before that are no longer needed.
    pub removed: Vec<String>,
    /// Existing files scpm didn't generate, left alone (see `--force`).
    pub skipped: Vec<String>,
    /// IntelliJ module per scpm module: module name → variant id.
    pub modules: BTreeMap<String, String>,
    pub libraries: usize,
    pub sources: SourcesReport,
    pub warnings: Vec<String>,
}

impl Summary {
    /// The warning about files left alone, if any. `scpm idea` always shows it; the
    /// automatic refresh only when it rewrote something, so it doesn't repeat on every command.
    pub fn skipped_warning(&self) -> Option<String> {
        if self.skipped.is_empty() {
            return None;
        }
        let modules_note = if self.skipped.iter().any(|s| s == ".idea/modules.xml") {
            " (with .idea/modules.xml skipped, IntelliJ won't see scpm's modules)"
        } else {
            ""
        };
        Some(format!(
            "left {} IntelliJ file{} that scpm didn't generate alone{modules_note}: {}; run `scpm idea --force` to replace them",
            self.skipped.len(),
            if self.skipped.len() == 1 { "" } else { "s" },
            self.skipped.join(", ")
        ))
    }
}

/// Whether `scpm idea` ran in this workspace before (so `scpm install` keeps it fresh).
pub fn generated_before(root: &Path) -> bool {
    root.join(MANIFEST).is_file()
}

/// XML attribute/text escaping.
pub fn esc(s: &str) -> String {
    let mut out = String::with_capacity(s.len());
    for c in s.chars() {
        match c {
            '&' => out.push_str("&amp;"),
            '<' => out.push_str("&lt;"),
            '>' => out.push_str("&gt;"),
            '"' => out.push_str("&quot;"),
            '\'' => out.push_str("&apos;"),
            c => out.push(c),
        }
    }
    out
}

/// IntelliJ's file name for a library (`scpm: org:a:1.0` → `scpm__org_a_1_0`): every character
/// other than an ASCII letter or digit becomes `_`, so IntelliJ keeps the file name when it
/// saves the library itself.
pub fn library_file_name(name: &str) -> String {
    name.chars().map(|c| if c.is_ascii_alphanumeric() { c } else { '_' }).collect()
}

/// Library file names, unique per library: [`library_file_name`] maps `foo-bar` and `foo_bar`
/// alike, so a later library whose readable name is taken gets a short hash of its name.
#[derive(Default)]
struct LibraryFiles {
    /// file name → library name
    used: BTreeMap<String, String>,
}

impl LibraryFiles {
    fn file_for(&mut self, name: &str) -> String {
        let readable = library_file_name(name);
        let file = match self.used.get(&readable) {
            Some(owner) if owner != name => format!("{readable}_{}", &crate::ide::sha256_hex(name.as_bytes())[..8]),
            _ => readable,
        };
        self.used.insert(file.clone(), name.to_string());
        file
    }
}

/// `Scala_2_13`, `Scala_3_9`: intellij-scala's `ScalaLanguageLevel` for a full version.
pub fn language_level(scala: &str) -> String {
    let parts: Vec<&str> = scala.split(['.', '-']).take(2).collect();
    format!("Scala_{}", parts.join("_"))
}

/// IntelliJ's `LanguageLevel` name for a Java release: `JDK_1_8`, `JDK_17`.
pub fn java_language_level(release: &str) -> String {
    match release.parse::<u32>() {
        Ok(n) if n <= 8 => format!("JDK_1_{n}"),
        _ => format!("JDK_{release}"),
    }
}

/// The IntelliJ scope of a classpath entry from the lists it is on.
fn scope(compile: bool, runtime: bool) -> Option<&'static str> {
    match (compile, runtime) {
        (true, true) => None,
        (true, false) => Some("PROVIDED"),
        (false, true) => Some("RUNTIME"),
        (false, false) => Some("TEST"),
    }
}

fn scope_attr(scope: Option<&str>) -> String {
    scope.map(|s| format!(" scope=\"{s}\"")).unwrap_or_default()
}

/// Path macros: `$PROJECT_DIR$/…` inside the workspace, `$USER_HOME$/…` under the home
/// directory, else the absolute path.
struct Paths {
    root: PathBuf,
    home: Option<PathBuf>,
}

impl Paths {
    /// A relative path (e.g. under `COURSIER_CACHE=./cache`) made absolute against the current
    /// directory first, as [`super::file_uri`] does; IntelliJ can't resolve `jar://./cache/…`.
    fn absolute(path: &Path) -> PathBuf {
        std::path::absolute(path).unwrap_or_else(|_| path.to_path_buf())
    }

    fn project(&self, path: &Path) -> String {
        let path = &Self::absolute(path);
        if let Ok(rel) = path.strip_prefix(&self.root) {
            return format!("$PROJECT_DIR$/{}", slash_path(rel));
        }
        if let Some(rel) = self.home.as_ref().and_then(|h| path.strip_prefix(h).ok()) {
            return format!("$USER_HOME$/{}", slash_path(rel));
        }
        slash_path(path)
    }

    /// From a module file in `.idea/modules/` (`$MODULE_DIR$`).
    fn module(&self, path: &Path) -> String {
        let path = &Self::absolute(path);
        match path.strip_prefix(&self.root) {
            Ok(rel) if rel.as_os_str().is_empty() => "$MODULE_DIR$/../..".to_string(),
            Ok(rel) => format!("$MODULE_DIR$/../../{}", slash_path(rel)),
            Err(_) => self.project(path),
        }
    }

    fn jar_url(&self, path: &Path) -> String {
        format!("jar://{}!/", self.project(path))
    }
}

fn xml_file(body: &str) -> String {
    format!("<?xml version=\"1.0\" encoding=\"UTF-8\"?>\n{MARKER}\n{body}")
}

fn library_xml(name: &str, jar: &str, sources: Option<&str>) -> String {
    let sources = match sources {
        Some(s) => format!("    <SOURCES>\n      <root url=\"{}\" />\n    </SOURCES>\n", esc(s)),
        None => "    <SOURCES />\n".to_string(),
    };
    xml_file(&format!(
        "<component name=\"libraryTable\">\n  <library name=\"{}\">\n    <CLASSES>\n      <root url=\"{}\" />\n    </CLASSES>\n    <JAVADOC />\n{sources}  </library>\n</component>\n",
        esc(name),
        esc(jar)
    ))
}

/// `bridge`: the compiler bridge jar URL, for Scala 3 (which ships its own bridge; the sbt and
/// Gradle importers set it too).
fn scala_sdk_xml(name: &str, scala: &str, classpath: &[String], bridge: Option<&str>) -> String {
    let roots: String = classpath.iter().map(|u| format!("        <root url=\"{}\" />\n", esc(u))).collect();
    let bridge = bridge
        .map(|b| format!("      <compiler-bridge-binary-jar>{}</compiler-bridge-binary-jar>\n", esc(b)))
        .unwrap_or_default();
    xml_file(&format!(
        "<component name=\"libraryTable\">\n  <library name=\"{}\" type=\"Scala\">\n    <properties>\n      <language-level>{}</language-level>\n      <compiler-classpath>\n{roots}      </compiler-classpath>\n{bridge}    </properties>\n    <CLASSES />\n    <JAVADOC />\n    <SOURCES />\n  </library>\n</component>\n",
        esc(name),
        language_level(scala)
    ))
}

fn scala_sdk_name(scala: &str) -> String {
    format!("scpm: scala-sdk-{scala}")
}

fn library_name(key: &str) -> String {
    format!("scpm: {key}")
}

/// The JDK name and language level for `misc.xml`: the major version of the JDK scpm uses.
fn project_jdk(tc: &Toolchain) -> Option<String> {
    let from_release =
        crate::worker::java_home().and_then(|h| fs::read_to_string(h.join("release")).ok()).and_then(|r| {
            let line = r.lines().find(|l| l.starts_with("JAVA_VERSION="))?.to_string();
            let version = line.trim_start_matches("JAVA_VERSION=").trim_matches('"').to_string();
            crate::install::jdk_major(&version)
        });
    from_release.or_else(|| tc.ws.config.toolchain.jdk.as_deref().and_then(crate::install::jdk_major))
}

/// The project SDK name for `misc.xml`. scpm names the SDK by the JDK's major version (`21`),
/// so an existing numeric name is scpm's and follows the current JDK, keeping the name and the
/// language level in step. A custom name (`corretto-21`) is one the user chose and is kept.
fn misc_jdk_name(existing: Option<&str>, project_jdk: Option<&str>) -> Option<String> {
    match existing {
        Some(name) if !name.is_empty() && !name.chars().all(|c| c.is_ascii_digit() || c == '.') => {
            Some(name.to_string())
        }
        other => project_jdk.or(other).map(str::to_string),
    }
}

/// The value of attribute `name` on the first element containing `marker` in `xml`.
fn attribute<'a>(xml: &'a str, marker: &str, name: &str) -> Option<&'a str> {
    let start = xml.find(marker)?;
    let element = &xml[start..start + xml[start..].find('>')?];
    let needle = format!("{name}=\"");
    let at = element.find(&needle)? + needle.len();
    Some(&element[at..at + element[at..].find('"')?])
}

/// Every `filepath="…"` in an existing `modules.xml`.
fn module_filepaths(xml: &str) -> Vec<String> {
    let mut out = Vec::new();
    let mut rest = xml;
    while let Some(i) = rest.find("filepath=\"") {
        rest = &rest[i + "filepath=\"".len()..];
        if let Some(end) = rest.find('"') {
            out.push(rest[..end].replace("&amp;", "&").replace("&quot;", "\""));
            rest = &rest[end..];
        }
    }
    out
}

struct ModuleXml<'a> {
    v: &'a Variant,
    module_dir: PathBuf,
    sdk: Option<String>,
    language_level: Option<String>,
    libraries: Vec<(String, Option<&'static str>)>,
    modules: Vec<(String, Option<&'static str>)>,
    /// Upstream variants that aren't IntelliJ modules: (variant id, classes dir, scope).
    /// Its roots are the classes directory and the variant's resource directories, as on scpm's
    /// runtime classpath (scpm doesn't copy resources into `classes`).
    module_libraries: Vec<(String, Vec<PathBuf>, Option<&'static str>)>,
    excludes: Vec<PathBuf>,
    /// Directories outside the module directory that another module already has as a content
    /// root (IntelliJ allows each directory in one module only).
    taken: BTreeSet<PathBuf>,
}

/// A variant's source and resource directories, absolute, with their `sourceFolder` attributes.
fn source_folders(root: &Path, v: &Variant) -> Vec<(PathBuf, &'static str)> {
    let mut folders = Vec::new();
    for (dirs, attrs) in [
        (&v.sources, "isTestSource=\"false\""),
        (&v.test_sources, "isTestSource=\"true\""),
        (&v.resources, "type=\"java-resource\""),
        (&v.test_resources, "type=\"java-test-resource\""),
    ] {
        for d in dirs {
            folders.push((root.join(d), attrs));
        }
    }
    folders
}

fn module_xml(paths: &Paths, m: &ModuleXml) -> String {
    let root = &paths.root;
    let v = m.v;
    let out = root.join(".scpm/idea-out").join(&v.id);
    let folders = source_folders(root, v);
    let folder = |(dir, attrs): &(PathBuf, &str)| {
        format!("      <sourceFolder url=\"file://{}\" {attrs} />\n", esc(&paths.module(dir)))
    };
    let (inside, outside): (Vec<_>, Vec<_>) = folders.iter().partition(|(d, _)| d.starts_with(&m.module_dir));
    let mut content = String::new();
    // Folders outside the module directory (e.g. `../shared`) get their own content roots.
    for f in outside.iter().filter(|(d, _)| !m.taken.contains(d)) {
        content.push_str(&format!(
            "    <content url=\"file://{}\">\n{}    </content>\n",
            esc(&paths.module(&f.0)),
            folder(f)
        ));
    }
    content.push_str(&format!("    <content url=\"file://{}\">\n", esc(&paths.module(&m.module_dir))));
    for f in &inside {
        content.push_str(&folder(f));
    }
    for e in &m.excludes {
        content.push_str(&format!("      <excludeFolder url=\"file://{}\" />\n", esc(&paths.module(e))));
    }
    content.push_str("    </content>\n");

    let mut entries = String::from(
        "    <orderEntry type=\"inheritedJdk\" />\n    <orderEntry type=\"sourceFolder\" forTests=\"false\" />\n",
    );
    if let Some(sdk) = &m.sdk {
        entries.push_str(&format!("    <orderEntry type=\"library\" name=\"{}\" level=\"project\" />\n", esc(sdk)));
    }
    for (name, s) in &m.libraries {
        entries.push_str(&format!(
            "    <orderEntry type=\"library\"{} name=\"{}\" level=\"project\" />\n",
            scope_attr(*s),
            esc(name)
        ));
    }
    // Module dependencies after libraries, as GenIdea does; they are not exported because each
    // module already lists its whole (jointly resolved) classpath.
    for (name, s) in &m.modules {
        entries.push_str(&format!(
            "    <orderEntry type=\"module\" module-name=\"{}\"{} />\n",
            esc(name),
            scope_attr(*s)
        ));
    }
    for (id, dirs, s) in &m.module_libraries {
        let roots: String =
            dirs.iter().map(|d| format!("          <root url=\"file://{}\" />\n", esc(&paths.module(d)))).collect();
        entries.push_str(&format!(
            "    <orderEntry type=\"module-library\"{}>\n      <library name=\"{}\">\n        <CLASSES>\n{roots}        </CLASSES>\n        <JAVADOC />\n        <SOURCES />\n      </library>\n    </orderEntry>\n",
            scope_attr(*s),
            esc(&format!("scpm: {id} (scpm output)")),
        ));
    }
    let level = m.language_level.as_ref().map(|l| format!(" LANGUAGE_LEVEL=\"{l}\"")).unwrap_or_default();
    xml_file(&format!(
        "<module type=\"JAVA_MODULE\" version=\"4\">\n  <component name=\"NewModuleRootManager\"{level} inherit-compiler-output=\"false\">\n    <output url=\"file://{}\" />\n    <output-test url=\"file://{}\" />\n    <exclude-output />\n{content}{entries}  </component>\n</module>\n",
        esc(&paths.module(&out.join("classes"))),
        esc(&paths.module(&out.join("test-classes")))
    ))
}

/// Generates the IntelliJ files and writes those that changed.
/// The lock's classpaths already hold each variant's whole upstream closure, so no graph is
/// needed.
pub fn generate(tc: &Toolchain, opts: &Options) -> Result<Summary, IdeError> {
    let ws = tc.ws;
    let root = &ws.root;
    let paths = Paths { root: root.clone(), home: dirs::home_dir().and_then(|h| h.canonicalize().ok().or(Some(h))) };
    let mut summary = Summary::default();
    let primaries: BTreeMap<&str, &Variant> =
        ws.modules.iter().map(|m| (m.name.as_str(), m.primary_variant())).collect();
    let is_primary = |id: &str| primaries.values().any(|v| v.id == id);

    // Every artifact any primary variant uses, for sources jars and library files.
    let mut keys: BTreeSet<String> = BTreeSet::new();
    for v in primaries.values() {
        let vlock = tc.lock.variants.get(&v.id).ok_or_else(|| InstallError::Stale(vec![v.id.clone()]))?;
        for kind in ClasspathKind::ALL {
            for e in kind.entries(vlock) {
                if let ClasspathEntry::Artifact(k) = e
                    && is_jar(k)
                {
                    keys.insert(k.clone());
                }
            }
        }
    }
    let (sources, report) = sources_jars(tc, &keys, opts.sources, &mut summary.warnings);
    summary.sources = report;

    // path (relative to the root) → content
    let mut files: BTreeMap<String, String> = BTreeMap::new();
    let mut library_files = LibraryFiles::default();
    for key in &keys {
        let name = library_name(key);
        let src = sources_module(key).and_then(|m| sources.get(&m)).map(|p| paths.jar_url(p));
        files.insert(
            format!(".idea/libraries/{}.xml", library_files.file_for(&name)),
            library_xml(&name, &paths.jar_url(&tc.file(key)), src.as_deref()),
        );
    }
    summary.libraries = keys.len();
    let scalas: BTreeSet<String> =
        primaries.values().filter_map(|v| v.scala.as_ref().map(|s| s.full.clone())).collect();
    for scala in &scalas {
        let name = scala_sdk_name(scala);
        let mut cp: Vec<String> = tc
            .boot(&format!("scala-compiler@{scala}"))?
            .iter()
            .map(|p| format!("file://{}", paths.project(p)))
            .collect();
        cp.sort();
        let bridge = if crate::coord::scala_binary_version(scala) == "3" {
            tc.boot(&crate::install::bridge_boot(scala))?.first().map(|p| format!("file://{}", paths.project(p)))
        } else {
            None
        };
        files.insert(
            format!(".idea/libraries/{}.xml", library_files.file_for(&name)),
            scala_sdk_xml(&name, scala, &cp, bridge.as_deref()),
        );
    }

    // Modules, and scalac settings grouped into profiles.
    let mut profiles: BTreeMap<(Vec<String>, Vec<String>), Vec<String>> = BTreeMap::new();
    let project_jdk = project_jdk(tc);
    // Out-of-tree directories (`../shared`) already used as a content root, by module.
    let mut claimed: BTreeMap<PathBuf, String> = BTreeMap::new();
    for m in &ws.modules {
        let v = m.primary_variant();
        let module_dir = root.join(&m.dir);
        let mut taken = BTreeSet::new();
        for (dir, _) in source_folders(root, v).into_iter().filter(|(d, _)| !d.starts_with(&module_dir)) {
            match claimed.get(&dir) {
                Some(owner) if owner != &m.name => {
                    summary.warnings.push(format!(
                        "{}: {} is already a content root of IntelliJ module `{owner}`; IntelliJ allows a directory in one module only, so `{}` doesn't get it",
                        m.name,
                        slash_path(dir.strip_prefix(root).unwrap_or(&dir)),
                        m.name
                    ));
                    taken.insert(dir);
                }
                Some(_) => {}
                None => {
                    claimed.insert(dir, m.name.clone());
                }
            }
        }
        let vlock = &tc.lock.variants[&v.id];
        let lists: Vec<HashSet<&ClasspathEntry>> =
            ClasspathKind::ALL.iter().map(|k| k.entries(vlock).iter().collect()).collect();
        let entry_scope = |e: &ClasspathEntry| scope(lists[0].contains(e), lists[1].contains(e));
        let mut libraries = Vec::new();
        let mut modules = Vec::new();
        let mut module_libraries = Vec::new();
        let mut seen = HashSet::new();
        for kind in ClasspathKind::ALL {
            for e in kind.entries(vlock) {
                if !seen.insert(e) {
                    continue;
                }
                match e {
                    ClasspathEntry::Artifact(k) if is_jar(k) => libraries.push((library_name(k), entry_scope(e))),
                    ClasspathEntry::Artifact(_) => {}
                    ClasspathEntry::Module { module } => {
                        let Some(up) = ws.variant(module) else { continue };
                        if is_primary(module) {
                            modules.push((up.module.clone(), entry_scope(e)));
                        } else {
                            summary.warnings.push(format!(
                                "{}: {} is not the IntelliJ module of `{}` (that is {}), so IntelliJ uses scpm's compiled output for it; run `scpm compile` first, or set `ide.primary` in {}",
                                m.name,
                                module,
                                up.module,
                                primaries[up.module.as_str()].id,
                                slash_path(&Path::new(&ws.module(&up.module).map(|u| u.dir.clone()).unwrap_or_default()).join("scpm.yaml"))
                            ));
                            let mut roots = vec![classes_dir(root, module)];
                            roots.extend(up.resources.iter().map(|r| root.join(r)));
                            module_libraries.push((module.clone(), roots, entry_scope(e)));
                        }
                    }
                }
            }
        }
        let opts = compiler_options(tc, v)?;
        if v.scala.is_some() {
            // `compilerPlugins` go to the profile's plugin list; a `-Xplugin:` written in
            // `scalacOptions` stays a parameter, as scpm passes it.
            let plugin_opts: Vec<String> = opts.plugins.iter().map(|p| format!("-Xplugin:{}", p.display())).collect();
            let params: Vec<String> = opts.scalac.iter().filter(|o| !plugin_opts.contains(o)).cloned().collect();
            let plugins: Vec<String> = opts.plugins.iter().map(|p| slash_path(p)).collect();
            profiles.entry((params, plugins)).or_default().push(m.name.clone());
        }
        let excludes = if m.dir == "." {
            [".scpm", ".metals", ".bsp", ".idea"].iter().map(|d| root.join(d)).collect()
        } else {
            Vec::new()
        };
        // The Java target scpm compiles for (`release`, else the toolchain JDK) when it differs
        // from the project JDK, so IntelliJ rejects what `scpm compile` would.
        let language_level =
            opts.release.as_ref().filter(|r| Some(*r) != project_jdk.as_ref()).map(|r| java_language_level(r));
        let xml = module_xml(
            &paths,
            &ModuleXml {
                v,
                module_dir,
                sdk: v.scala.as_ref().map(|s| scala_sdk_name(&s.full)),
                language_level,
                libraries,
                modules,
                module_libraries,
                excludes,
                taken,
            },
        );
        files.insert(format!(".idea/modules/{}.iml", m.name), xml);
        summary.modules.insert(m.name.clone(), v.id.clone());
    }

    let mut profile_list: Vec<(String, Vec<String>, Vec<String>)> =
        profiles.into_iter().map(|((params, plugins), mods)| (mods.join(","), params, plugins)).collect();
    profile_list.sort();
    let mut compiler = String::from("<project version=\"4\">\n  <component name=\"ScalaCompilerConfiguration\">\n");
    for (i, (mods, params, plugins)) in profile_list.iter().enumerate() {
        compiler.push_str(&format!(
            "    <profile name=\"scpm {}\" modules=\"{}\">\n      <parameters>\n",
            i + 1,
            esc(mods)
        ));
        for p in params {
            compiler.push_str(&format!("        <parameter value=\"{}\" />\n", esc(p)));
        }
        compiler.push_str("      </parameters>\n      <plugins>\n");
        for p in plugins {
            compiler.push_str(&format!("        <plugin path=\"{}\" />\n", esc(p)));
        }
        compiler.push_str("      </plugins>\n    </profile>\n");
    }
    compiler.push_str("  </component>\n</project>\n");
    files.insert(".idea/scala_compiler.xml".into(), xml_file(&compiler));

    // modules.xml: ours, plus entries for modules scpm didn't generate.
    let previous: BTreeSet<String> =
        fs::read_to_string(root.join(MANIFEST)).map(|t| t.lines().map(str::to_string).collect()).unwrap_or_default();
    let ours: BTreeSet<String> =
        files.keys().filter(|p| p.ends_with(".iml")).map(|p| format!("$PROJECT_DIR$/{p}")).collect();
    let was_ours = |fp: &str| fp.strip_prefix("$PROJECT_DIR$/").is_some_and(|p| previous.contains(p));
    let mut module_paths: Vec<String> = ours.iter().cloned().collect();
    if let Ok(existing) = fs::read_to_string(root.join(".idea/modules.xml")) {
        for fp in module_filepaths(&existing) {
            if !ours.contains(&fp) && !was_ours(&fp) && !module_paths.contains(&fp) {
                module_paths.push(fp);
            }
        }
    }
    module_paths.sort();
    let entries: String = module_paths
        .iter()
        .map(|fp| format!("      <module fileurl=\"file://{0}\" filepath=\"{0}\" />\n", esc(fp)))
        .collect();
    files.insert(
        ".idea/modules.xml".into(),
        xml_file(&format!(
            "<project version=\"4\">\n  <component name=\"ProjectModuleManager\">\n    <modules>\n{entries}    </modules>\n  </component>\n</project>\n"
        )),
    );

    // misc.xml (project JDK): only when there is none, or it is still ours (or `--force`).
    let misc_path = root.join(".idea/misc.xml");
    let misc_existing = fs::read_to_string(&misc_path).ok();
    if opts.force || misc_existing.as_deref().is_none_or(|t| t.contains(MARKER)) {
        let existing_name =
            misc_existing.as_deref().and_then(|t| attribute(t, "ProjectRootManager", "project-jdk-name"));
        match misc_jdk_name(existing_name, project_jdk.as_deref()) {
            Some(jdk_name) => {
                let level = project_jdk
                    .as_deref()
                    .map(|j| format!(" languageLevel=\"{}\"", java_language_level(j)))
                    .unwrap_or_default();
                files.insert(
                    ".idea/misc.xml".into(),
                    xml_file(&format!(
                        "<project version=\"4\">\n  <component name=\"ProjectRootManager\" version=\"2\"{level} project-jdk-name=\"{}\" project-jdk-type=\"JavaSDK\">\n    <output url=\"file://$PROJECT_DIR$/.scpm/idea-out/project\" />\n  </component>\n</project>\n",
                        esc(&jdk_name)
                    )),
                );
            }
            None => summary.warnings.push("no JDK found (set JAVA_HOME); .idea/misc.xml not written".into()),
        }
    }

    // Write only what is ours: missing files, files with our marker, and files we wrote last
    // time (IntelliJ drops the comment when it re-saves a file). Anything else is skipped.
    for (rel, content) in &files {
        let path = root.join(rel);
        if !opts.force
            && let Ok(existing) = fs::read(&path)
            && !String::from_utf8_lossy(&existing).contains(MARKER)
            && !previous.contains(rel)
        {
            summary.skipped.push(rel.clone());
            continue;
        }
        if write_if_changed(&path, content)? {
            summary.written.push(rel.clone());
        }
    }
    files.retain(|rel, _| !summary.skipped.contains(rel));
    // Remove what we generated before and no longer generate (modules and libraries only).
    for rel in previous.iter().filter(|p| !files.contains_key(*p)) {
        if (rel.starts_with(".idea/modules/") || rel.starts_with(".idea/libraries/scpm__"))
            && fs::remove_file(root.join(rel)).is_ok()
        {
            summary.removed.push(rel.clone());
        }
    }
    let manifest: String = files.keys().map(|p| format!("{p}\n")).collect();
    write_if_changed(&root.join(MANIFEST), &manifest)?;
    Ok(summary)
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn names_and_levels() {
        assert_eq!(
            library_file_name("scpm: org.typelevel:cats-core_3:2.13.0"),
            "scpm__org_typelevel_cats_core_3_2_13_0"
        );
        let mut files = LibraryFiles::default();
        assert_eq!(files.file_for("scpm: com.acme:foo-bar:1.0"), "scpm__com_acme_foo_bar_1_0");
        let other = files.file_for("scpm: com.acme:foo_bar:1.0");
        assert!(
            other.starts_with("scpm__com_acme_foo_bar_1_0_") && other.len() == "scpm__com_acme_foo_bar_1_0_".len() + 8,
            "{other}"
        );
        assert_eq!(files.file_for("scpm: com.acme:foo-bar:1.0"), "scpm__com_acme_foo_bar_1_0");
        assert_eq!(language_level("3.9.0"), "Scala_3_9");
        assert_eq!(language_level("2.13.18"), "Scala_2_13");
        assert_eq!(language_level("3.10.0-RC1"), "Scala_3_10");
        assert_eq!(java_language_level("8"), "JDK_1_8");
        assert_eq!(java_language_level("17"), "JDK_17");
    }

    #[test]
    fn scopes() {
        assert_eq!(scope(true, true), None);
        assert_eq!(scope(true, false), Some("PROVIDED"));
        assert_eq!(scope(false, true), Some("RUNTIME"));
        assert_eq!(scope(false, false), Some("TEST"));
    }

    #[test]
    fn reads_existing_files() {
        let misc = r#"<project version="4"><component name="ProjectRootManager" version="2" project-jdk-name="corretto-21" project-jdk-type="JavaSDK"/></project>"#;
        assert_eq!(attribute(misc, "ProjectRootManager", "project-jdk-name"), Some("corretto-21"));
        let modules = r#"<module fileurl="file://$PROJECT_DIR$/a.iml" filepath="$PROJECT_DIR$/a.iml" /><module filepath="$PROJECT_DIR$/b &amp; c.iml"/>"#;
        assert_eq!(module_filepaths(modules), ["$PROJECT_DIR$/a.iml", "$PROJECT_DIR$/b & c.iml"]);
    }

    #[test]
    fn path_macros() {
        // Platform-absolute fixtures: on Windows `/ws` gains a drive prefix, as production
        // paths do once `std::path::absolute` has normalized them.
        let abs = |p: &str| std::path::absolute(p).unwrap();
        let (root, home, opt) = (abs("/ws"), abs("/home/u"), abs("/opt/x.jar"));
        let paths = Paths { root: root.clone(), home: Some(home.clone()) };
        assert_eq!(paths.module(&root.join("m/src")), "$MODULE_DIR$/../../m/src");
        assert_eq!(paths.module(&root), "$MODULE_DIR$/../..");
        assert_eq!(paths.project(&home.join(".cache/x.jar")), "$USER_HOME$/.cache/x.jar");
        assert_eq!(paths.jar_url(&opt), format!("jar://{}!/", slash_path(&opt)));
        assert_eq!(esc("a<\"&'>"), "a&lt;&quot;&amp;&apos;&gt;");
        // Relative paths (`COURSIER_CACHE=./cache`) resolve against the current directory.
        let cwd = std::env::current_dir().unwrap();
        let here = Paths { root: cwd.clone(), home: None };
        assert_eq!(here.jar_url(Path::new("./cache/x.jar")), "jar://$PROJECT_DIR$/cache/x.jar!/");
        assert_eq!(here.module(Path::new("cache/x")), "$MODULE_DIR$/../../cache/x");
        let elsewhere = Paths { root: PathBuf::from("/ws-not-here"), home: None };
        assert_eq!(elsewhere.project(Path::new("cache/x.jar")), slash_path(&cwd.join("cache/x.jar")));
    }

    #[test]
    fn misc_jdk_names() {
        // scpm's numeric name follows the current JDK, with the language level.
        assert_eq!(misc_jdk_name(Some("17"), Some("21")).as_deref(), Some("21"));
        assert_eq!(misc_jdk_name(Some("1.8"), Some("21")).as_deref(), Some("21"));
        assert_eq!(misc_jdk_name(Some("17"), None).as_deref(), Some("17"));
        // A name the user chose is kept.
        assert_eq!(misc_jdk_name(Some("corretto-21"), Some("25")).as_deref(), Some("corretto-21"));
        assert_eq!(misc_jdk_name(None, Some("25")).as_deref(), Some("25"));
        assert_eq!(misc_jdk_name(None, None), None);
    }
}
